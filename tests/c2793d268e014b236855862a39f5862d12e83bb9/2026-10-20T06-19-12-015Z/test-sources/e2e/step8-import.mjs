import { chromium } from 'playwright-core';
import { readFileSync } from 'node:fs';
import JSZip from 'jszip';
const B='http://localhost:3123';
const boot=readFileSync(process.env.SERVER_LOG,'utf8').match(/(http:\/\/localhost:3123\/signup\?code=[\w-]+)/)[1];
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH});
const context=await browser.newContext({viewport:{width:1600,height:1000}});
const page=await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const check=(ok,label)=>{console.log(`${ok?'PASS':'FAIL'} ${label}`);if(!ok)process.exitCode=1;};
try {
 await page.goto(boot);await page.waitForLoadState('networkidle');
 await page.fill('#name','Import Tester');await page.fill('#email','admin@example.test');
 await page.fill('#password','correct horse battery staple');await page.fill('#confirm','correct horse battery staple');
 await page.click('button.primary');await page.waitForURL(B+'/');
 await page.goto(B+'/admin');await page.locator('tr',{hasText:'editor.dos-shell'}).locator('button').click();await page.waitForLoadState('networkidle');
 const zip=new JSZip();
 zip.file('[Content_Types].xml','<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="xml" ContentType="application/xml"/><Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/></Types>');
 zip.file('_rels/.rels','<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="r1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/></Relationships>');
 const lines=['Summary','Operations leader','Skills','ITIL; Vendor management'];
 zip.file('word/document.xml',`<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body>${lines.map(t=>`<w:p><w:r><w:t>${t}</w:t></w:r></w:p>`).join('')}</w:body></w:document>`);
 const bytes=await zip.generateAsync({type:'nodebuffer'});
 await page.goto(B+'/edit/imports');
 await page.locator('#cv').setInputFiles({name:'operations.docx',mimeType:'application/vnd.openxmlformats-officedocument.wordprocessingml.document',buffer:bytes});
 await page.getByRole('button',{name:'Upload and review'}).click();await page.waitForURL(/\/edit\/imports\/[\w-]+$/);
 const reviewURL=page.url();
 check(await page.inputValue('#module-0')==='summary','Word import creates a summary suggestion');
 check(await page.inputValue('#items-1')==='ITIL\nVendor management','skills extracted into items');
 const original=await context.request.get(reviewURL+'/original');
 check(original.status()===200&&(await original.body()).equals(bytes),'original download retains exact bytes');
 const other=await browser.newContext();
 const anonymous=await other.request.get(reviewURL+'/original',{maxRedirects:0});
 check(anonymous.status()===303,'original download requires authentication');await other.close();
 await page.fill('#text-0','Reviewed operations leader');
 await page.locator('#items-1').focus();await page.keyboard.press('End');await page.keyboard.press('Enter');await page.keyboard.type('Service delivery');
 check((await page.inputValue('#items-1')).endsWith('\nService delivery'),'bullets support adding new lines while typing');
 await page.getByText('Target emphasis (optional)',{exact:true}).first().click();
 await page.fill('#roles','Operations');await page.selectOption('#basis','confirmed');
 await page.getByRole('button',{name:'Save review draft',exact:true}).click();await page.waitForLoadState('networkidle');
 check(await page.inputValue('#text-0')==='Reviewed operations leader','review corrections survive save');
 check((await page.inputValue('#items-1')).includes('Service delivery'),'new bullet survives draft save');
 await page.screenshot({path:`${process.env.OUT}/shot-import-review.png`,fullPage:true});
 await page.getByRole('button',{name:'Approve and add to library',exact:true}).click();await page.getByRole('status').filter({hasText:'This CV was added'}).waitFor();
 check(true,'approval adds content and saves composition');
 const exported=await (await context.request.get(B+'/account/export')).json();
 check(exported.content.length===2,'only approved entries are added');
 check(exported.library.compositions.length===1,'composition is saved');
 check(exported.imports.originals[0].bytes===bytes.toString('base64'),'account export includes the original');
 await page.goto(B+'/edit/content/summary');
 check((await page.textContent('main')).includes('Summary'),'imported content is accessible in current editor');
 const skillEntry=exported.content.find(entry=>entry.module==='skills');
 await page.goto(B+'/edit/content/entry/'+skillEntry.id);
 await page.getByRole('button',{name:'+ Another wording',exact:true}).first().click();
 await page.fill('#ew-new','Applied in service delivery and governance');
 await page.locator('form.wording.new button.primary').click();
 await page.locator('#ew-t0').waitFor();
 await page.reload();
 check(await page.inputValue('#ew-t0')==='Applied in service delivery and governance','skills descriptions can be added and edited in the library');
 await page.goto(reviewURL);await page.reload();
 const again=await (await context.request.get(B+'/account/export')).json();
 check(again.content.length===2,'revisiting approval does not duplicate content');
 check(errors.length===0,`no browser errors ${errors.join(' | ')}`);
} finally {await browser.close();}
