import { chromium } from 'playwright-core';
import { readFileSync } from 'node:fs';
const bootUrl = readFileSync(process.env.SERVER_LOG, 'utf8').match(/(http:\/\/localhost:3123\/signup\?code=[\w-]+)/)[1];
const B = 'http://localhost:3123', PW = 'correct horse battery staple';
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH });
const p = await (await browser.newContext({ viewport: { width: 1280, height: 900 } })).newPage();
const errs = []; p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
const check = (c, l) => { console.log(`${c ? 'PASS' : 'FAIL'} ${l}`); if (!c) process.exitCode = 1; };
await p.goto(bootUrl); await p.waitForLoadState('networkidle');
await p.fill('#name', 'Admin'); await p.fill('#email', 'admin@example.test'); await p.fill('#password', PW); await p.fill('#confirm', PW);
await p.click('button.primary'); await p.waitForURL(B + '/');
await p.click('text=Assemble'); await p.click('text=Load example content');
check(await p.locator('#category').isVisible(), 'example content loaded');
await p.selectOption('#category', { label: 'IT governance roles' }); await p.locator('form:has(#category) button').click(); await p.waitForURL(/category=/);
const gov = await p.frameLocator('iframe.preview').locator('main').textContent();
check(/IT operations leader — governance/.test(gov) && !/Tailspin/.test(gov), 'governance CV: governance headline, early career dropped');
await p.screenshot({ path: `${process.env.OUT}/shot-4-assemble-gov.png`, fullPage: true });
await p.selectOption('#target', { label: 'Example Insurance plc — Head of IT Risk & Compliance' }); await p.locator('form:has(#target) button').click(); await p.waitForURL(/target=/);
await p.frameLocator('iframe.preview[src*="target="]').locator('main').filter({ hasText: 'NIS2 readiness' }).waitFor();
const t = await p.frameLocator('iframe.preview[src*="target="]').locator('main').textContent();
check(/NIS2 readiness/.test(t) && t.indexOf('Certifications') < t.indexOf('Experience'), 'job target: NIS2 summary, credentials before experience');
check((await p.content()).includes('matches job tags: nis2'), 'trace explains the job-tag choice');
await p.click('text=Load example content').catch(() => {});
const again = await p.request.post(B + '/assemble?/loadDemo', { form: {}, headers: { origin: B } });
check((await again.text()).includes('empty account'), 'example cannot be loaded twice');
const other = await p.request.get(B + '/assemble?target=does-not-exist');
check(other.status() === 404, 'unknown/foreign target gives 404');
await p.goto(B + '/admin');
await p.locator('tr', { hasText: 'editor.dos-shell' }).locator('button').click();
await p.goto(B + '/assemble');
await p.selectOption('#target', { label: 'Example Insurance plc — Head of IT Risk & Compliance' });
await p.locator('form:has(#target) button').click(); await p.waitForURL(/target=/);
const beforeCopy = await (await p.request.get(B + '/account/export')).json();
await p.getByRole('button', { name: 'Copy to Saved CVs', exact: true }).click();
await p.waitForURL(/\/edit\/cvs\/[\w-]+$/);
const afterCopy = await (await p.request.get(B + '/account/export')).json();
check(afterCopy.library.compositions.length === 1, 'legacy job can be copied into an independent saved CV');
check(JSON.stringify(afterCopy.library.compositions[0].document).includes('NIS2 readiness'), 'copy preserves the selected job wording');
check(JSON.stringify(beforeCopy.content) === JSON.stringify(afterCopy.content) && JSON.stringify(beforeCopy.jobs) === JSON.stringify(afterCopy.jobs), 'copy leaves library and legacy job untouched');
const missingCopy = await p.request.post(B + '/assemble?/saveCopy', { form: { target: 'does-not-exist' }, headers: { origin: B } });
check(missingCopy.status() === 404, 'copy rejects an unknown or foreign job');
check(errs.length === 0, 'no console errors ' + errs.join('|'));
await browser.close();
